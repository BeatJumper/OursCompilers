// 常量折叠测试程序
int main() {
    // 整数常量折叠测试
    int a = 3 + 5;        // 应该折叠为 8
    int b = 10 - 4;       // 应该折叠为 6
    int c = 6 * 7;        // 应该折叠为 42
    int d = 20 / 4;       // 应该折叠为 5
    
    // 浮点数常量折叠测试
    float e = 1.5 + 2.5;  // 应该折叠为 4.0
    float f = 5.0 - 1.5;  // 应该折叠为 3.5
    float g = 2.0 * 3.0;  // 应该折叠为 6.0
    float h = 8.0 / 2.0;  // 应该折叠为 4.0
    
    // 混合类型常量折叠测试
    float i = 3 + 2.5;    // 应该折叠为 5.5
    float j = 10 - 1.5;   // 应该折叠为 8.5
    float k = 4 * 2.5;    // 应该折叠为 10.0
    float l = 15 / 3.0;   // 应该折叠为 5.0
    
    // 复杂表达式（嵌套常量折叠）
    int m = (2 + 3) * (4 - 1);  // 应该折叠为 5 * 3 = 15
    float n = (1.5 + 2.5) / (2.0 - 1.0);  // 应该折叠为 4.0 / 1.0 = 4.0
    
    return a + b + c + d;
}
