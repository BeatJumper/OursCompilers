int main(){
    // 测试数组到单个元素的赋值
    int arr[1] = {42};
    int x = arr[0];  // 这应该能正常工作

    // 测试嵌套数组的情况
    int nested[1][1] = {{99}};
    int y = nested[0][0];  // 这也应该能正常工作

    // 测试我们修复的情况：数组初始化中的数组值
    int c[2][1] = {6, 7};
    int result[2][1] = {{c[0][0]}, {c[1][0]}};  // 这是我们修复的情况

    return x + y + result[0][0] + result[1][0];  // 应该返回 42 + 99 + 6 + 7 = 154
}
