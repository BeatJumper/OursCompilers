// 取余运算测试
int main() {
    // ===== 基本取余运算测试 =====
    
    // 简单取余
    int mod1 = 10 % 3;          // 应该折叠为 1
    int mod2 = 15 % 4;          // 应该折叠为 3
    int mod3 = 20 % 5;          // 应该折叠为 0
    int mod4 = 7 % 2;           // 应该折叠为 1
    
    // 大数取余
    int mod5 = 100 % 7;         // 应该折叠为 2
    int mod6 = 999 % 13;        // 应该折叠为 11
    
    // ===== 嵌套取余表达式 =====
    
    // 取余与其他运算结合
    int complex1 = (10 + 5) % 4;        // 应该折叠为 15 % 4 = 3
    int complex2 = (20 * 3) % 7;        // 应该折叠为 60 % 7 = 4
    int complex3 = (100 / 2) % 6;       // 应该折叠为 50 % 6 = 2
    
    // 多层嵌套
    int nested1 = ((8 + 2) % 3) + 1;    // 应该折叠为 (10 % 3) + 1 = 1 + 1 = 2
    int nested2 = 5 * (12 % 5);         // 应该折叠为 5 * 2 = 10
    
    // ===== 边界情况测试 =====
    
    // 被除数小于除数
    int small1 = 3 % 5;         // 应该折叠为 3
    int small2 = 1 % 10;        // 应该折叠为 1
    
    // 被除数等于除数
    int equal1 = 5 % 5;         // 应该折叠为 0
    int equal2 = 13 % 13;       // 应该折叠为 0
    
    // 除数为1
    int div_one1 = 42 % 1;      // 应该折叠为 0
    int div_one2 = 999 % 1;     // 应该折叠为 0
    
    // ===== 负数取余测试 =====
    
    // 注意：这部分可能需要特殊处理，因为C语言中负数取余的结果依赖于实现
    // int neg1 = (-10) % 3;       // 结果可能是 -1 或 2，取决于实现
    // int neg2 = 10 % (-3);       // 结果可能是 1 或 -2，取决于实现
    
    // ===== 输出验证 =====
    
    putint(mod1);       // 应该输出 1
    putint(mod2);       // 应该输出 3
    putint(mod3);       // 应该输出 0
    putint(complex1);   // 应该输出 3
    putint(nested1);    // 应该输出 2
    
    return mod1 + mod2 + mod3;  // 应该返回 1 + 3 + 0 = 4
}
